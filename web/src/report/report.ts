import type { Diagnosis, EntityRef, Finding, Pin, ThreadGroup, TypeRow } from '../contracts.gen';
import { refFor } from '../entities';
import { colors, fonts } from '../styles/tokens';

export interface ReportSections {
  verdict: boolean;
  findings: boolean;
  infoFindings: boolean;
  pins: boolean;
  threads: boolean;
  heap: boolean;
}

export const defaultSections: ReportSections = {
  verdict: true,
  findings: true,
  infoFindings: false,
  pins: true,
  threads: false,
  heap: false,
};

export interface ReportInput {
  diagnosis: Diagnosis;
  pins: Pin[];
  threadGroups?: ThreadGroup[];
  heapTypes?: TypeRow[];
  generatedAt: Date;
  appVersion?: string;
}

export interface Report {
  title: string;
  fileName: string;
  markdown: string;
  html: string;
}

/**
 * The incident report. One model, two renderings: Markdown for tickets and chat, and a
 * self-contained HTML page (inline styles, no scripts, no external assets) for sharing and
 * printing. All text from the dump is escaped; finding markup (`code`, {{uri}}) is rendered
 * as code spans and entity labels.
 */
export function buildReport(input: ReportInput, sections: ReportSections): Report {
  const { diagnosis: d, pins } = input;
  const entities = [...d.verdict.entities, ...d.findings.flatMap((f) => f.evidence), ...pins.map(pinRef)];
  const app = (d.dump.processName ?? d.dump.fileName).replace(/\.(exe|dll)$/i, '');
  const top = d.findings[0];
  const title =
    top && d.verdict.severity !== 'ok'
      ? `${app}: ${plainText(top.title, entities)}`
      : `${app}: ${plainText(d.verdict.headline, entities)}`;
  const shown = d.findings.filter(
    (f) => f.severity === 'critical' || f.severity === 'warning' || (sections.infoFindings && f.severity === 'info'),
  );
  const blocks: Block[] = [];

  blocks.push({ kind: 'meta', text: `Incident report · generated ${stamp(input.generatedAt)}` });
  blocks.push({ kind: 'h1', text: title });
  blocks.push({
    kind: 'sub',
    text: `${d.dump.fileName} · ${d.dump.runtime} ${d.dump.architecture} · ${size(d.dump.fileSizeBytes)} · ${d.dump.threadCount} threads`,
  });

  if (sections.verdict) {
    blocks.push({ kind: 'h2', text: 'Summary' });
    blocks.push({ kind: 'p', rich: `**${d.verdict.headline}** ${d.verdict.body}` });
    if (d.vitals.length) {
      blocks.push({
        kind: 'table',
        head: ['Vital', 'Value', 'Detail'],
        rows: d.vitals.map((v) => [v.label, v.value, v.detail]),
      });
    }
  }

  if (sections.findings && shown.length) {
    const recommended = shown[0];
    blocks.push({ kind: 'h2', text: shown.length === 1 ? 'Finding' : 'Findings' });
    for (const f of shown) {
      blocks.push(...findingBlocks(f, pins));
    }

    blocks.push({ kind: 'h2', text: 'Recommended actions' });
    blocks.push({ kind: 'ol', items: recommended.nextSteps });
  }

  if (sections.pins && pins.length) {
    blocks.push({ kind: 'h2', text: 'Pins & notes' });
    blocks.push({
      kind: 'ul',
      items: pins.map((p) => `{{${p.uri}}}${p.note ? ` — ${p.note.replace(/[{}`]/g, '')}` : ''}`),
    });
  }

  if (sections.threads && input.threadGroups?.length) {
    blocks.push({ kind: 'h2', text: 'Thread groups' });
    blocks.push({
      kind: 'table',
      head: ['Threads', 'Where', 'Doing', 'State'],
      rows: input.threadGroups.map((g) => [String(g.count), g.where, g.request ?? '—', g.stateLabel]),
      mono: [1, 2],
    });
  }

  if (sections.heap && input.heapTypes?.length) {
    blocks.push({ kind: 'h2', text: 'Top heap types' });
    blocks.push({
      kind: 'table',
      head: ['Type', 'Count', 'Size'],
      rows: input.heapTypes.slice(0, 20).map((t) => [t.name, t.count.toLocaleString('en-US'), size(t.size)]),
      mono: [0],
    });
  }

  blocks.push({
    kind: 'footer',
    text: `Generated by Dump Debugger${input.appVersion ? ` ${input.appVersion}` : ''} from ${d.dump.path}. Analysis ${d.seconds.toFixed(1)} s. Findings are produced by deterministic analyzers and carry a confidence level; verify before acting.`,
  });

  const fileName = `incident-${slug(app)}-${input.generatedAt.toISOString().slice(0, 10)}`;
  return { title, fileName, markdown: toMarkdown(blocks, entities), html: toHtml(title, blocks, entities) };
}

type Block =
  | { kind: 'meta' | 'h1' | 'h2' | 'h3' | 'sub' | 'footer'; text: string }
  | { kind: 'p' | 'note'; rich: string }
  | { kind: 'ol' | 'ul'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][]; mono?: number[] };

function findingBlocks(f: Finding, pins: Pin[]): Block[] {
  const out: Block[] = [
    { kind: 'h3', text: `${sev(f.severity)} · ${plainText(f.title, f.evidence)}` },
    { kind: 'p', rich: `${f.why} · ${cap(f.confidence)} confidence` },
    { kind: 'p', rich: f.whatItMeans },
  ];
  if (f.evidence.length) {
    out.push({
      kind: 'ul',
      items: f.evidence.map((e) => `{{${e.uri}}}${e.detail && e.kind !== 'lock' ? ` · ${e.detail}` : ''}`),
    });
  }
  for (const p of pins.filter(
    (p) => p.note && (p.uri === `finding/${f.id}` || f.evidence.some((e) => e.uri === p.uri)),
  )) {
    out.push({ kind: 'note', rich: `**Note on {{${p.uri}}}:** ${p.note.replace(/[{}`]/g, '')}` });
  }
  return out;
}

// ---------- Markdown ----------

function toMarkdown(blocks: Block[], entities: EntityRef[]): string {
  const md = (s: string) => richToMarkdown(s, entities);
  const lines: string[] = [];
  for (const b of blocks) {
    switch (b.kind) {
      case 'meta':
        lines.push(`_${escMd(b.text)}_`, '');
        break;
      case 'h1':
        lines.push(`# ${escMd(b.text)}`, '');
        break;
      case 'sub':
        lines.push(`\`${b.text}\``, '');
        break;
      case 'h2':
        lines.push(`## ${escMd(b.text)}`, '');
        break;
      case 'h3':
        lines.push(`### ${escMd(b.text)}`, '');
        break;
      case 'p':
        lines.push(md(b.rich), '');
        break;
      case 'note':
        lines.push(`> ${md(b.rich)}`, '');
        break;
      case 'ol':
        b.items.forEach((s, i) => lines.push(`${i + 1}. ${md(s)}`));
        lines.push('');
        break;
      case 'ul':
        b.items.forEach((s) => lines.push(`- ${md(s)}`));
        lines.push('');
        break;
      case 'table':
        lines.push(`| ${b.head.map(escCell).join(' | ')} |`, `|${b.head.map(() => '---').join('|')}|`);
        b.rows.forEach((r) =>
          lines.push(
            `| ${r.map((c, i) => (b.mono?.includes(i) ? `\`${c.replace(/`/g, '')}\`` : escCell(c))).join(' | ')} |`,
          ),
        );
        lines.push('');
        break;
      case 'footer':
        lines.push('---', '', `_${escMd(b.text)}_`, '');
        break;
    }
  }
  return lines.join('\n');
}

function richToMarkdown(s: string, entities: EntityRef[]): string {
  return s
    .split(/(`[^`]+`|\{\{[^}]+\}\}|\*\*[^*]+\*\*)/g)
    .map((part) => {
      if (part.startsWith('`')) return part;
      if (part.startsWith('{{')) return `\`${refFor(part.slice(2, -2), entities).label}\``;
      if (part.startsWith('**')) return `**${richToMarkdown(part.slice(2, -2), entities)}**`;
      return escMd(part);
    })
    .join('');
}

// ---------- HTML ----------

function toHtml(title: string, blocks: Block[], entities: EntityRef[]): string {
  const rich = (s: string) => richToHtml(s, entities);
  const body = blocks
    .map((b) => {
      switch (b.kind) {
        case 'meta':
          return `<div class="lbl">${esc(b.text)}</div>`;
        case 'h1':
          return `<h1>${esc(b.text)}</h1>`;
        case 'sub':
          return `<p class="sub">${esc(b.text)}</p>`;
        case 'h2':
          return `<h2>${esc(b.text)}</h2>`;
        case 'h3':
          return `<h3>${esc(b.text)}</h3>`;
        case 'p':
          return `<p>${rich(b.rich)}</p>`;
        case 'note':
          return `<div class="note">${rich(b.rich)}</div>`;
        case 'ol':
          return `<ol>${b.items.map((s) => `<li>${rich(s)}</li>`).join('')}</ol>`;
        case 'ul':
          return `<ul>${b.items.map((s) => `<li>${rich(s)}</li>`).join('')}</ul>`;
        case 'table':
          return `<table><thead><tr>${b.head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${b.rows
            .map(
              (r) =>
                `<tr>${r.map((c, i) => `<td${b.mono?.includes(i) ? ' class="mono"' : ''}>${esc(c)}</td>`).join('')}</tr>`,
            )
            .join('')}</tbody></table>`;
        case 'footer':
          return `<footer>${esc(b.text)}</footer>`;
      }
    })
    .join('\n');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
:root{color-scheme:dark}
*{box-sizing:border-box}
body{margin:0;background:${colors.bg0};color:${colors.fg1};font:14px/1.55 ${fonts.sans};padding:28px 16px}
.paper{max-width:760px;margin:0 auto;background:${colors.bg1};border:1px solid ${colors.line};border-radius:10px;padding:40px 48px}
h1,h2,h3{color:${colors.fg0};font-weight:600;letter-spacing:-.01em;margin:0}
h1{font-size:24px;line-height:1.25;margin-top:8px}
h2{font-size:16px;margin:26px 0 8px}
h3{font-size:14px;margin:18px 0 4px}
p{margin:8px 0}
.sub{font-family:${fonts.mono};font-size:12px;color:${colors.fg3}}
.lbl{font-size:11px;color:${colors.fg3};text-transform:uppercase;letter-spacing:.06em;font-weight:600}
code,.mono{font-family:${fonts.mono};font-size:12.5px;color:${colors.fg0}}
code{background:${colors.bg3};border:1px solid ${colors.line2};border-radius:4px;padding:0 5px}
ol,ul{padding-left:20px}li{margin:4px 0}
.note{border-left:2px solid ${colors.warn};padding:6px 12px;background:${colors.warnDim};border-radius:0 6px 6px 0;font-size:13px;margin:10px 0}
table{width:100%;border-collapse:collapse;font-size:13px;margin:8px 0}
th{text-align:left;color:${colors.fg2};font-weight:500;font-size:11.5px;text-transform:uppercase;letter-spacing:.05em;padding:6px 8px;border-bottom:1px solid ${colors.line}}
td{padding:6px 8px;border-bottom:1px solid ${colors.line};vertical-align:top}
footer{margin-top:30px;padding-top:14px;border-top:1px solid ${colors.line};font-size:12px;color:${colors.fg3}}
strong{color:${colors.fg0}}
@media print{:root{color-scheme:light}body{background:#fff;color:#1a1d22;padding:0}.paper{border:0;padding:0;max-width:none;background:#fff}h1,h2,h3,strong,code,.mono{color:#000}code{background:#f1f3f5;border-color:#d0d5dc}.note{background:#fff7e6}th,td{border-color:#d0d5dc}}
</style>
</head>
<body>
<article class="paper">
${body}
</article>
</body>
</html>
`;
}

function richToHtml(s: string, entities: EntityRef[]): string {
  return s
    .split(/(`[^`]+`|\{\{[^}]+\}\}|\*\*[^*]+\*\*)/g)
    .map((part) => {
      if (part.startsWith('`') && part.endsWith('`') && part.length > 1)
        return `<code>${esc(part.slice(1, -1))}</code>`;
      if (part.startsWith('{{')) return `<code>${esc(refFor(part.slice(2, -2), entities).label)}</code>`;
      if (part.startsWith('**')) return `<strong>${richToHtml(part.slice(2, -2), entities)}</strong>`;
      return esc(part);
    })
    .join('');
}

// ---------- helpers ----------

function pinRef(p: Pin): EntityRef {
  return { uri: p.uri, kind: p.kind, label: p.label, detail: null };
}

export function plainText(s: string, entities: EntityRef[]): string {
  return s.replace(/\{\{([^}]+)\}\}/g, (_, u: string) => refFor(u, entities).label).replace(/`/g, '');
}

export function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escMd(s: string): string {
  return s.replace(/([\\*_[\]<>#|])/g, '\\$1');
}

function escCell(s: string): string {
  return escMd(s).replace(/\n/g, ' ');
}

function sev(s: string): string {
  return s === 'critical' ? 'Critical' : s === 'warning' ? 'Warning' : s === 'info' ? 'Info' : 'OK';
}

function cap(s: string): string {
  return s[0].toUpperCase() + s.slice(1);
}

function size(n: number): string {
  const u = ['B', 'KB', 'MB', 'GB'];
  let v = n;
  let i = 0;
  while (v >= 1024 && i < u.length - 1) {
    v /= 1024;
    i++;
  }
  return i === 0 ? `${n} B` : `${v.toFixed(v >= 100 ? 0 : 1)} ${u[i]}`;
}

function stamp(d: Date): string {
  return `${d.toISOString().slice(0, 10)} ${d.toISOString().slice(11, 16)} UTC`;
}

function slug(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'dump'
  );
}
