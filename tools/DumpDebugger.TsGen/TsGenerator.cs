using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using DumpDebugger.Core.Rpc;

namespace DumpDebugger.TsGen;

/// <summary>
/// Reflects over <see cref="RpcCatalog"/> and every contract type reachable from it, and emits
/// TypeScript: one interface per record, a string-union (plus a values array) per enum, and
/// typed <c>RpcMethods</c>/<c>RpcNotifications</c> maps the web client is generic over. Names
/// and enum values follow <see cref="ContractJson"/> (camelCase), so what TS sees is exactly
/// what System.Text.Json writes.
/// </summary>
public static class TsGenerator
{
    private static readonly NullabilityInfoContext Nullability = new();

    public static string Generate()
    {
        var types = new SortedDictionary<string, Type>(StringComparer.Ordinal);
        var queue = new Queue<Type>();

        void Enqueue(Type t)
        {
            foreach (var named in NamedTypesIn(t))
            {
                var name = TsName(named);
                if (types.TryGetValue(name, out var existing))
                {
                    if (existing != named)
                    {
                        throw new InvalidOperationException($"Two contract types map to TS name '{name}': {existing} and {named}.");
                    }

                    continue;
                }

                types[name] = named;
                queue.Enqueue(named);
            }
        }

        foreach (var m in RpcCatalog.Methods)
        {
            Enqueue(m.Params);
            Enqueue(m.Result);
        }

        foreach (var n in RpcCatalog.Notifications)
        {
            Enqueue(n.Payload);
        }

        foreach (var extra in RpcCatalog.ExtraExportedTypes)
        {
            Enqueue(extra);
        }

        while (queue.Count > 0)
        {
            var t = queue.Dequeue();
            if (t.IsEnum)
            {
                continue;
            }

            foreach (var p in ContractProperties(t))
            {
                Enqueue(p.PropertyType);
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   Generated by tools/DumpDebugger.TsGen from DumpDebugger.Core (RpcCatalog + contracts).");
        sb.AppendLine("//   Do not edit by hand: run `npm run gen:types` in web/.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("/* eslint-disable */");
        sb.AppendLine();

        foreach (var (name, type) in types)
        {
            if (type.IsEnum)
            {
                var values = Enum.GetNames(type).Select(CamelCase).ToList();
                sb.AppendLine($"export type {name} = {string.Join(" | ", values.Select(v => $"'{v}'"))};");
                sb.AppendLine($"export const {name}Values: readonly {name}[] = [{string.Join(", ", values.Select(v => $"'{v}'"))}];");
                sb.AppendLine();
                continue;
            }

            var props = ContractProperties(type).ToList();
            if (props.Count == 0)
            {
                sb.AppendLine($"export type {name} = Record<string, never>;");
                sb.AppendLine();
                continue;
            }

            var summary = type.GetCustomAttribute<TsDocAttribute>()?.Text;
            if (summary is not null)
            {
                sb.AppendLine($"/** {summary} */");
            }

            sb.AppendLine($"export interface {name} {{");
            foreach (var p in props)
            {
                var info = Nullability.Create(p);
                sb.AppendLine($"  {JsonName(p)}: {TsType(p.PropertyType, info)};");
            }

            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("/** Every bridge method: its params and result. Host methods run in DumpDebugger.Host; the rest are forwarded to the worker. */");
        sb.AppendLine("export interface RpcMethods {");
        foreach (var m in RpcCatalog.Methods)
        {
            sb.AppendLine($"  '{m.Name}': {{ params: {TsType(m.Params, null)}; result: {TsType(m.Result, null)} }};");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export type RpcMethod = keyof RpcMethods;");
        sb.AppendLine();
        sb.AppendLine("/** Server-pushed notifications and their payloads. */");
        sb.AppendLine("export interface RpcNotifications {");
        foreach (var n in RpcCatalog.Notifications)
        {
            sb.AppendLine($"  '{n.Name}': {TsType(n.Payload, null)};");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export type RpcNotification = keyof RpcNotifications;");
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static IEnumerable<PropertyInfo> ContractProperties(Type t) =>
        t.GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.GetIndexParameters().Length == 0
                        && p.Name != "EqualityContract"
                        && p.GetCustomAttribute<JsonIgnoreAttribute>() is not { Condition: JsonIgnoreCondition.Always })
            .OrderBy(p => p.MetadataToken);

    private static IEnumerable<Type> NamedTypesIn(Type t)
    {
        if (Nullable.GetUnderlyingType(t) is { } underlying)
        {
            foreach (var x in NamedTypesIn(underlying))
            {
                yield return x;
            }

            yield break;
        }

        if (t.IsArray)
        {
            foreach (var x in NamedTypesIn(t.GetElementType()!))
            {
                yield return x;
            }

            yield break;
        }

        if (t.IsGenericType)
        {
            foreach (var arg in t.GetGenericArguments())
            {
                foreach (var x in NamedTypesIn(arg))
                {
                    yield return x;
                }
            }

            if (IsCollection(t) || IsDictionary(t))
            {
                yield break;
            }
        }

        if (IsContract(t))
        {
            yield return t;
        }
    }

    private static bool IsContract(Type t) =>
        t.Namespace?.StartsWith("DumpDebugger.Core", StringComparison.Ordinal) == true
        && (t.IsEnum || t.IsClass || (t.IsValueType && !t.IsPrimitive))
        && !t.IsGenericTypeDefinition;

    private static string TsName(Type t)
    {
        if (!t.IsGenericType)
        {
            return t.Name;
        }

        // Page<ThreadGroup> → PageOfThreadGroup
        var root = t.Name[..t.Name.IndexOf('`')];
        return root + "Of" + string.Join("And", t.GetGenericArguments().Select(TsName));
    }

    private static string TsType(Type t, NullabilityInfo? info)
    {
        var nullable = info?.ReadState == NullabilityState.Nullable;
        if (Nullable.GetUnderlyingType(t) is { } underlying)
        {
            return TsType(underlying, null) + " | null";
        }

        string core;
        if (t == typeof(string) || t == typeof(Guid) || t == typeof(DateTimeOffset) || t == typeof(DateTime) || t == typeof(TimeSpan))
        {
            core = "string";
        }
        else if (t == typeof(bool))
        {
            core = "boolean";
        }
        else if (t.IsPrimitive || t == typeof(decimal))
        {
            core = "number";
        }
        else if (t == typeof(JsonElement) || t == typeof(object))
        {
            core = "unknown";
        }
        else if (t.IsArray)
        {
            core = Wrap(TsType(t.GetElementType()!, info?.ElementType)) + "[]";
        }
        else if (IsDictionary(t))
        {
            var args = t.GetGenericArguments();
            core = $"Record<string, {TsType(args[1], info?.GenericTypeArguments.ElementAtOrDefault(1))}>";
        }
        else if (IsCollection(t))
        {
            core = Wrap(TsType(t.GetGenericArguments()[0], info?.GenericTypeArguments.ElementAtOrDefault(0))) + "[]";
        }
        else if (IsContract(t))
        {
            core = TsName(t);
        }
        else
        {
            throw new InvalidOperationException($"No TypeScript mapping for {t}.");
        }

        return nullable ? core + " | null" : core;
    }

    private static string Wrap(string ts) => ts.Contains(' ') ? $"({ts})" : ts;

    private static bool IsCollection(Type t) =>
        t.IsGenericType && t.GetGenericTypeDefinition() is var d
        && (d == typeof(IReadOnlyList<>) || d == typeof(List<>) || d == typeof(IList<>) || d == typeof(IEnumerable<>)
            || d == typeof(IReadOnlyCollection<>) || d == typeof(ICollection<>));

    private static bool IsDictionary(Type t) =>
        t.IsGenericType && t.GetGenericTypeDefinition() is var d
        && (d == typeof(IReadOnlyDictionary<,>) || d == typeof(Dictionary<,>) || d == typeof(IDictionary<,>));

    private static string JsonName(PropertyInfo p) =>
        p.GetCustomAttribute<JsonPropertyNameAttribute>()?.Name ?? CamelCase(p.Name);

    private static string CamelCase(string name) => JsonNamingPolicy.CamelCase.ConvertName(name);
}
